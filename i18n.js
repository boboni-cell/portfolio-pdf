  let currentLang = "zh";
  const i18nElements = [];

  // Collect all data-i18n elements and store their Chinese text
  document.querySelectorAll("[data-i18n]").forEach(el => {
    i18nElements.push({
      el: el,
      key: el.getAttribute("data-i18n"),
      zh: el.textContent.trim()
    });
  });

  function switchLang(lang) {
    if (lang === currentLang) return;
    currentLang = lang;

    i18nElements.forEach(item => {
      if (lang === "ko") {
        // Save current Chinese text before switching
        item.zh = item.el.textContent.trim();
        if (I18N_KO[item.key]) {
          item.el.textContent = I18N_KO[item.key];
        }
      } else {
        // Restore Chinese
        if (item.zh) {
          item.el.textContent = item.zh;
        }
      }
    });

    // Update lang attribute on html element
    document.documentElement.lang = lang === "ko" ? "ko" : "zh-CN";

    // Update button states
    document.querySelectorAll(".lang-btn").forEach(btn => {
      btn.classList.toggle("active", btn.dataset.lang === lang);
    });
  }

  // Expose for button onclick
  window.switchLang = switchLang;
